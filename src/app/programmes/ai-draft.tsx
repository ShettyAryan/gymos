import { Stack as RouterStack, router } from 'expo-router';
import { useState } from 'react';

import { Button, Card, Notice, ProgressBar, Screen, StatusPill, Text } from '@/components';
import { useMutation, useQuery } from '@/data/DatabaseProvider';
import { hasValidConsent } from '@/data/local/repositories/aiConsent';
import { getPreferences } from '@/data/local/repositories/settings';
import { AI_POLICY_VERSION } from '@/features/coach/disclosure';
import {
  generateProgrammeDraft,
  type DraftProgress,
  type DraftResult,
} from '@/features/coach/programmeDraft';

export default function AiDraftScreen() {
  const gate = useQuery(
    async (db) =>
      (await getPreferences(db)).aiEnabled && (await hasValidConsent(db, AI_POLICY_VERSION)),
  );
  const [progress, setProgress] = useState<DraftProgress | null>(null);
  const [result, setResult] = useState<DraftResult | null>(null);
  const gen = useMutation((db) => generateProgrammeDraft(db, setProgress));

  const start = async () => {
    setResult(null);
    setResult(await gen.run());
  };

  return (
    <Screen edges={['bottom']}>
      <RouterStack.Screen options={{ title: 'AI programme draft' }} />
      <Notice
        tone="info"
        title="How this works"
        message="The AI drafts days and exercises from your profile and your own exercise library, one day at a time (to stay within the free AI limits). The result is saved as a draft for you to review, edit and approve. Nothing becomes active automatically."
      />
      {gate.data === false ? (
        <Card>
          <Text>Enable the AI coach first.</Text>
          <Button label="Review AI data notice" onPress={() => router.push('/settings/ai')} />
        </Card>
      ) : (
        <Button
          label={result?.ok ? 'Generate another draft' : 'Generate draft'}
          onPress={start}
          loading={gen.pending}
        />
      )}
      {gen.pending && progress ? (
        <Card>
          <Text>{progress.step}</Text>
          <ProgressBar
            value={progress.total ? progress.done / progress.total : 0}
            label={progress.step}
          />
        </Card>
      ) : null}
      {result && !result.ok ? (
        <Notice tone="warning" title="No draft created" message={result.message} />
      ) : null}
      {result?.ok ? (
        <Card>
          <StatusPill label="Draft — not active" tone="warning" />
          <Text variant="heading">{result.programme.name}</Text>
          <Text variant="caption" faint>
            Generated by {result.model}
            {result.mock ? ' (mock)' : ''}
          </Text>
          {result.warnings.map((w) => (
            <Notice key={w} tone="warning" message={w} />
          ))}
          <Button
            label="Review, edit & approve"
            onPress={() =>
              router.replace({ pathname: '/programmes/[id]', params: { id: result.programme.id } })
            }
          />
        </Card>
      ) : null}
      <Text variant="caption" faint>
        AI output is checked against your exercise library and programme safety limits before it is
        saved. It can still be wrong — review every exercise.
      </Text>
    </Screen>
  );
}
