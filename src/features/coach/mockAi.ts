import type {
  AiRequest,
  CoachAnswer,
  ProgrammeDayDraft,
  ProgrammeOutline,
  WeeklyNarrative,
} from '../../../supabase/functions/_shared/schemas';

/**
 * Development-only mock AI (no credentials, no network). Deterministic outputs derived from the
 * request so the full draft → review → approve flow can be exercised offline. Always labelled
 * "Mock AI" in the UI; never used when a real backend is configured unless explicitly enabled.
 */
export const MOCK_MODEL = 'mock-ai (development)';

export function mockAiOutput(req: AiRequest): unknown {
  switch (req.task) {
    case 'programme_draft': {
      if (req.input.stage === 'outline') {
        const p = req.input.profile;
        const n = Math.min(Math.max(p.sessionsPerWeek ?? 3, 1), 6);
        const days = p.preferredWeekdays.length
          ? p.preferredWeekdays.slice(0, n)
          : [1, 3, 5, 2, 4, 6].slice(0, n);
        const titles =
          n <= 2
            ? ['Full Body A', 'Full Body B']
            : n === 3
              ? ['Full Body A', 'Full Body B', 'Full Body C']
              : ['Upper A', 'Lower A', 'Upper B', 'Lower B', 'Upper C', 'Lower C'];
        const out: ProgrammeOutline = {
          programmeName: `Mock ${n}-day plan`,
          summary: `A ${n}-day programme generated by the development mock.`,
          rationale: 'Mock output for testing the draft and approval flow. Not real coaching.',
          assumptions: ['Generated without a real AI model.'],
          caveats: ['Review every exercise before approving.'],
          days: days.map((wd, i) => ({
            title: titles[i] ?? `Day ${i + 1}`,
            focus: titles[i]?.startsWith('Lower')
              ? 'legs'
              : titles[i]?.startsWith('Upper')
                ? 'upper body'
                : 'full body',
            weekday: wd,
            intendedMinutes: p.sessionMinutes ?? 60,
          })),
        };
        return out;
      }
      const { catalogue, day } = req.input;
      const wantLegs = /leg|lower/i.test(`${day.title} ${day.focus ?? ''}`);
      const wantUpper = /upper/i.test(`${day.title} ${day.focus ?? ''}`);
      const legPatterns = ['squat', 'hinge', 'lunge', 'leg_isolation'];
      const pool = catalogue.filter((c) =>
        wantLegs
          ? legPatterns.includes(c.pattern)
          : wantUpper
            ? !legPatterns.includes(c.pattern) && c.pattern !== 'conditioning'
            : c.pattern !== 'conditioning',
      );
      const picked = (pool.length ? pool : catalogue).slice(0, 4);
      const out: ProgrammeDayDraft = {
        rationale: 'Mock selection from your available exercises.',
        caveats: ['Mock output — not real coaching.'],
        exercises: picked.map((c, i) => ({
          exerciseId: c.id,
          sets: i === 0 ? 3 : 2,
          repMin: i === 0 ? 6 : 10,
          repMax: i === 0 ? 10 : 15,
          restSeconds: i === 0 ? 150 : 90,
          targetRir: 2,
          priority: i === 0 ? 'primary' : i === 1 ? 'secondary' : 'accessory',
          alternativeIds: [],
          note: null,
        })),
      };
      return out;
    }
    case 'coach_question': {
      const out: CoachAnswer = {
        answer: `Mock answer (development mode). You asked: "${req.input.question.slice(0, 200)}". A real answer requires the AI backend.`,
        assumptions: [],
        caveats: ['Mock output — not real coaching.'],
        dataGaps:
          req.input.context.recentSessions.length === 0 ? ['No recent sessions logged.'] : [],
        proposedChanges: [],
        safetyNote: /pain|injur|hurt|dizzy|chest/i.test(req.input.question)
          ? 'If you have pain or concerning symptoms, stop and consult a qualified professional.'
          : null,
      };
      return out;
    }
    case 'weekly_review_narrative': {
      const out: WeeklyNarrative = {
        summary: 'Mock weekly narrative (development mode) based only on your recorded facts.',
        highlights: [],
        focusNextWeek: ['Keep the same plan; consistency first.'],
        caveats: ['Mock output — not real coaching.'],
      };
      return out;
    }
    case 'adaptation_explanation':
      return { explanation: 'Mock explanation (development mode).', caveats: [] };
  }
}
